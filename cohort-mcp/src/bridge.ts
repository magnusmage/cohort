import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

import { listTracked, readVaultFile } from "./git.js";
import { type VaultRecord, parseRecord } from "./record.js";

/**
 * Adoption bridge: generate the files teams already keep (AGENTS.md, CLAUDE.md,
 * Cursor rules) from the vault.
 *
 * Only verified records are rendered by default, so the files other agents read
 * carry trusted memory, not unverified agent-asserted claims. Superseded records
 * are left out. Rendering is deterministic (records sorted by id and grouped by
 * kind) and idempotent, so regenerating produces byte-identical files. The vault
 * stays the source of truth: a generated marker says hand edits are reabsorbed as
 * gated proposals (P4-2), not kept.
 */

const RECORD_DIRS = ["facts", "decisions", "threads"];

export const BRIDGE_TARGETS = ["AGENTS.md", "CLAUDE.md", ".cursor/rules/cohort.mdc"] as const;

export const GENERATED_MARKER =
  "<!-- cohort:generated. The Cohort vault is the source of truth. Hand edits here are reabsorbed as gated proposals, not kept. -->";

export interface BridgeOptions {
  includeQuarantined?: boolean;
}

export async function collectRecords(root: string, includeQuarantined: boolean): Promise<VaultRecord[]> {
  const tracked = await listTracked(root, ".");
  const files = tracked.filter((f) => f.endsWith(".md") && RECORD_DIRS.some((d) => f.startsWith(`${d}/`)));
  const out: VaultRecord[] = [];
  for (const f of files) {
    try {
      const record = parseRecord(await readVaultFile(root, f));
      if (record.meta.status === "superseded") continue;
      if (record.meta.status !== "verified" && !includeQuarantined) continue;
      out.push(record);
    } catch {
      // skip unreadable
    }
  }
  out.sort((a, b) => (a.meta.id < b.meta.id ? -1 : a.meta.id > b.meta.id ? 1 : 0));
  return out;
}

function section(title: string, records: VaultRecord[]): string {
  if (records.length === 0) return "";
  const bullets = records.map((r) => `- ${r.text.replace(/\s*\n\s*/g, " ").trim()}`).join("\n");
  return `## ${title}\n\n${bullets}`;
}

/** Render the canonical bridge body. Deterministic for a given record set. */
export function renderBridge(records: VaultRecord[]): string {
  const decisions = records.filter((r) => r.meta.kind === "decision");
  const facts = records.filter((r) => r.meta.kind === "fact");
  const threads = records.filter((r) => r.meta.kind === "thread");
  const parts = [
    "# Team memory (generated by Cohort)",
    GENERATED_MARKER,
    section("Decisions", decisions),
    section("Conventions and facts", facts),
    section("Open threads", threads),
  ].filter((p) => p.length > 0);
  return `${parts.join("\n\n")}\n`;
}

/** Render and write all bridge targets under the vault root. Idempotent. */
export async function generateBridge(
  root: string,
  opts: BridgeOptions = {},
): Promise<{ body: string; written: string[] }> {
  const records = await collectRecords(root, opts.includeQuarantined ?? false);
  const body = renderBridge(records);
  const written: string[] = [];
  for (const target of BRIDGE_TARGETS) {
    const abs = join(root, target);
    await mkdir(dirname(abs), { recursive: true });
    await writeFile(abs, body, "utf8");
    written.push(target);
  }
  return { body, written };
}

/** Default entry for the CLI: resolve the vault root from the environment. */
export async function defaultGenerateBridge(
  env: Record<string, string | undefined>,
  cwd: string,
  opts: BridgeOptions = {},
): Promise<{ body: string; written: string[] }> {
  const root = env.COHORT_VAULT_DIR ?? cwd;
  return generateBridge(root, opts);
}
